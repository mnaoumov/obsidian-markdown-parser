export interface RemarkObsidianCase {
  /**
   * The test file it came from.
   */
  readonly file: string;

  /**
   * Whether the test passed the plugin options, which Obsidian has no counterpart of.
   */
  readonly hasOptions: boolean;

  /**
   * The markdown.
   */
  readonly markdown: string;

  /**
   * The test it came from, its \`describe\` titles and its \`it\` title joined by \` > \`.
   */
  readonly test: string;
}

