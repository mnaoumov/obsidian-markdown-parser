/**
 * @file
 *
 * Imports the markdown inputs of `@quartz-community/remark-obsidian`'s test suites (MIT) into
 * `src/oracle/remark-obsidian/cases.ts`, so the worker oracle can measure them against Obsidian.
 *
 * The test files are read as text with the TypeScript compiler API and never run. An input is the first argument of a
 * call to a helper of the test file whose first parameter is the markdown (`parse`, `processWithGfm`, `shape`, ...),
 * when that argument is a constant: a string, a template without substitutions, a `+` of constants, an array of
 * constants joined by a constant, a `.repeat` by a number, or a `const` or `for ... of` variable bound to one of these.
 * Anything else is counted as skipped. A case keeps the test it came from and whether the test passed options, since
 * Obsidian has none and such a case may assert a behaviour Obsidian does not have.
 *
 * Usage: `jiti scripts/oracles/import-remark-obsidian.ts --source <remark-obsidian checkout> [--files a.test.ts,b.test.ts]`.
 */

