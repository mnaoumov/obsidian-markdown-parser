const DEFAULT_FILES = ['remark-obsidian.test.ts', 'collect.test.ts'];
const MARKDOWN_PARAMETER_NAMES = new Set(['markdown', 'md', 'source', 'text']);

const { values } = parseArgs({
  options: {
    files: { type: 'string' },
    source: { type: 'string' }
  }
});

if (values.source === undefined) {
  throw new Error('Pass --source <remark-obsidian checkout>.');
}

const source = values.source;
const files = values.files?.split(',') ?? DEFAULT_FILES;
const commit = execSync('git rev-parse HEAD', { cwd: source }).toString().trim();
const commitDate = execSync('git log -1 --format=%cI', { cwd: source }).toString().trim();
const version = (JSON.parse(readFileSync(join(source, 'package.json'), 'utf-8')) as PackageJson).version;

const cases: ExtractedCase[] = [];
const skippedArguments: Expression[] = [];

for (const file of files) {
  const text = readFileSync(join(source, 'test', file), 'utf-8');
  const sourceFile = createSourceFile(file, text, ScriptTarget.Latest, true);
  const helpers = collectHelpers(sourceFile);
  visit(sourceFile, file, helpers);
}

const seen = new Set<string>();
const unique = cases.filter((testCase) => {
  if (seen.has(testCase.markdown)) {
    return false;
  }
  seen.add(testCase.markdown);
  return true;
});

