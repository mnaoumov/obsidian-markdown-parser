// The names of the test file's functions whose first parameter is the markdown.
function collectHelpers(root: SourceFile): Set<string> {
  const names = new Set<string>();
  function walk(node: Node): void {
    if (isFunctionDeclaration(node) && node.name !== undefined && isMarkdownParameter(node.parameters[0])) {
      names.add(node.name.text);
    }
    if (
      isVariableDeclaration(node) && isIdentifier(node.name) && node.initializer !== undefined
      && (isArrowFunction(node.initializer) || isFunctionExpression(node.initializer))
      && isMarkdownParameter(node.initializer.parameters[0])
    ) {
      names.add(node.name.text);
    }
    forEachChild(node, walk);
  }
  walk(root);
  return names;
}

// The constant values an expression can take: one for a constant, several for a `for ... of` variable, none otherwise.
function evaluate(expression: Expression): null | string[] {
  let node = expression;
  while (isParenthesizedExpression(node)) {
    node = node.expression;
  }
  if (isStringLiteral(node) || isNoSubstitutionTemplateLiteral(node)) {
    return [node.text];
  }
  if (isBinaryExpression(node) && node.operatorToken.kind === SyntaxKind.PlusToken) {
    const left = evaluateOne(node.left);
    const right = evaluateOne(node.right);
    return left === null || right === null ? null : [left + right];
  }
  if (isCallExpression(node) && isPropertyAccessExpression(node.expression)) {
    const method = node.expression.name.text;
    const target = node.expression.expression;
    if (method === 'join' && isArrayLiteralExpression(target)) {
      const separator = node.arguments[0] === undefined ? ',' : evaluateOne(node.arguments[0]);
      const elements = target.elements.map((element) => evaluateOne(element));
      return separator === null || elements.includes(null) ? null : [elements.join(separator)];
    }
    if (method === 'repeat' && node.arguments[0] !== undefined && isNumericLiteral(node.arguments[0])) {
      const base = evaluateOne(target);
      return base === null ? null : [base.repeat(Number(node.arguments[0].text))];
    }
    return null;
  }
  return isIdentifier(node) ? resolveIdentifier(node) : null;
}

function evaluateOne(node: Expression): null | string {
  const result = evaluate(node);
  return result?.length === 1 ? result[0] ?? null : null;
}

// The initializer of a variable of the identifier's name declared by one of the statements before it.
function findInitializer(statements: readonly Statement[], identifier: Identifier): Expression | null {
  for (const statement of statements) {
    if (statement.pos >= identifier.pos || !isVariableStatement(statement)) {
      continue;
    }
    for (const declaration of statement.declarationList.declarations) {
      if (isIdentifier(declaration.name) && declaration.name.text === identifier.text && declaration.initializer !== undefined) {
        return declaration.initializer;
      }
    }
  }
  return null;
}

function isMarkdownParameter(parameter: ParameterDeclaration | undefined): boolean {
  return parameter !== undefined && isIdentifier(parameter.name) && MARKDOWN_PARAMETER_NAMES.has(parameter.name.text);
}

// The values of a variable: a `const` with a constant initializer, or a `for (const x of [...])` over constants.
function resolveIdentifier(identifier: Identifier): null | string[] {
  let scope: Node = identifier.parent;
  while (!isSourceFile(scope)) {
    if (isForOfStatement(scope) && isVariableDeclarationList(scope.initializer)) {
      const declaration = scope.initializer.declarations[0];
      if (declaration !== undefined && isIdentifier(declaration.name) && declaration.name.text === identifier.text) {
        if (!isArrayLiteralExpression(scope.expression)) {
          return null;
        }
        const elements = scope.expression.elements.map((element) => evaluateOne(element));
        return elements.includes(null) ? null : elements as string[];
      }
    }
    if (isBlock(scope)) {
      const initializer = findInitializer(scope.statements, identifier);
      if (initializer !== null) {
        return evaluate(initializer);
      }
    }
    scope = scope.parent;
  }
  const initializer = findInitializer(scope.statements, identifier);
  return initializer === null ? null : evaluate(initializer);
}

// The `describe` and `it` titles around a node, joined by ` > `.
function testName(node: Node): string {
  const titles: string[] = [];
  for (let current = node.parent; !isSourceFile(current); current = current.parent) {
    if (!(isCallExpression(current) && isIdentifier(current.expression) && ['describe', 'it', 'test'].includes(current.expression.text))) {
      continue;
    }

    const title = current.arguments[0];
    titles.unshift(title === undefined ? '?' : evaluateOne(title) ?? title.getText());
  }
  return titles.join(' > ');
}

function visit(node: Node, file: string, helpers: Set<string>): void {
  if (isCallExpression(node) && isIdentifier(node.expression) && helpers.has(node.expression.text) && node.arguments[0] !== undefined) {
    const markdowns = evaluate(node.arguments[0]);
    if (markdowns === null) {
      skippedArguments.push(node.arguments[0]);
    } else {
      for (const markdown of markdowns) {
        cases.push({ file, hasOptions: node.arguments.length > 1, markdown, test: testName(node) });
      }
    }
  }
  forEachChild(node, (child) => {
    visit(child, file, helpers);
  });
}
