/**
 * @file
 *
 * Writes the flat barrel the documentation site's API reference reads.
 *
 * The package's root entry `src/index.ts` re-exports the entry points in `src/entries/`, which re-export the modules
 * that declare each export. The site generator of `@mnaoumov/typescript-dev-toolkit` reads only the re-exports of the
 * barrel it is given, one level deep, so it would document the few names an entry point declares itself and nothing
 * else. This resolves every export of `src/index.ts` to the module that declares it and writes one `export { ... } from`
 * per module into the uncommitted `docs/src/generated-public-api.ts`.
 */

import {
  mkdirSync,
  writeFileSync
} from 'node:fs';
import {
  dirname,
  join,
  relative
} from 'node:path/posix';
import {
  createProgram,
  ModuleKind,
  ModuleResolutionKind,
  ScriptTarget,
  SymbolFlags
} from 'typescript';

import { PUBLIC_API_BARREL } from './docs-site-config.ts';

/**
 * Resolves every export of `src/index.ts` to its declaring module and writes {@link PUBLIC_API_BARREL}.
 *
 * @param root - The repository root.
 * @throws If an export is renamed on its way to `src/index.ts`, which the site generator cannot document.
 */
export function generatePublicApiBarrel(root: string): void {
  const entryFile = join(root, 'src', 'index.ts');
  const program = createProgram({
    options: {
      allowImportingTsExtensions: true,
      module: ModuleKind.NodeNext,
      moduleResolution: ModuleResolutionKind.NodeNext,
      noEmit: true,
      target: ScriptTarget.ES2024
    },
    rootNames: [entryFile]
  });
  const checker = program.getTypeChecker();
  const entrySourceFile = program.getSourceFile(entryFile);
  const entrySymbol = entrySourceFile === undefined ? undefined : checker.getSymbolAtLocation(entrySourceFile);
  if (entrySymbol === undefined) {
    throw new Error(`Could not read the exports of ${entryFile}`);
  }

  const namesByFile = new Map<string, string[]>();
  for (const exported of checker.getExportsOfModule(entrySymbol)) {
    // eslint-disable-next-line no-bitwise -- SymbolFlags is a bit set, and getAliasedSymbol asserts an alias.
    const isAlias = (exported.flags & SymbolFlags.Alias) !== 0;
    const declared = isAlias ? checker.getAliasedSymbol(exported) : exported;
    const declaration = declared.declarations?.[0];
    if (declaration === undefined) {
      throw new Error(`The export ${exported.name} of src/index.ts has no declaration`);
    }
    if (declared.name !== exported.name) {
      throw new Error(`src/index.ts exports ${declared.name} renamed to ${exported.name}, which the API reference cannot document`);
    }
    const fileName = declaration.getSourceFile().fileName;
    const names = namesByFile.get(fileName) ?? [];
    names.push(exported.name);
    namesByFile.set(fileName, names);
  }

  const barrelPath = join(root, PUBLIC_API_BARREL);
  const lines = [
    '// Generated by scripts/docs/docs-public-api.ts from the exports of src/index.ts. Not committed.',
    ''
  ];
  const files = [...namesByFile].toSorted(([a], [b]) => a.localeCompare(b));
  for (const [fileName, names] of files) {
    const specifier = relative(dirname(barrelPath), fileName);
    const sortedNames = names.toSorted((a, b) => a.localeCompare(b));
    lines.push(`export { ${sortedNames.join(', ')} } from '${specifier}';`);
  }
  mkdirSync(dirname(barrelPath), { recursive: true });
  writeFileSync(barrelPath, `${lines.join('\n')}\n`);
}
